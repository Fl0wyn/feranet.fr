/** Catégories d'outils traduites dans la langue demandée. */
export function getToolCategories(locale: Locale): ToolCategory[] {
  if (locale === "en") return toolCategories;
  return toolCategories.map((c) => ({
    title: CATEGORIES_FR[c.title] ?? c.title,
    items: c.items.map((t) => ({ ...t, detail: DETAILS_FR[`${c.title}/${t.app}`] ?? DETAILS_FR[t.app] ?? t.detail })),
  }));
}
